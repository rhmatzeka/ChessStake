#!/usr/bin/env node
// Embeds public/assets/chess into hashed CSS, so a dropped request can never leave the board half drawn.
// Run this after changing the art: node scripts/embed-chess-art.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const web = path.resolve(import.meta.dirname, "..");
const uri = (file) =>
  `data:image/png;base64,${readFileSync(path.join(web, "public/assets/chess", file)).toString("base64")}`;
const out = (file, css) => writeFileSync(path.join(web, "src/components/arena", file), css);
const header = "/* Generated by scripts/embed-chess-art.mjs. Do not edit by hand. */\n";

const NAMES = { p: "Pawn", n: "Knight", b: "Bishop", r: "Rook", q: "Queen", k: "King" };
const rules = [];
for (const [color, side] of [["w", "White"], ["b", "Black"]]) {
  for (const [kind, name] of Object.entries(NAMES)) {
    rules.push(`.chess-${color}${kind} { background-image: url(${uri(`${side}${name}.png`)}); }`);
  }
}
out(
  "chess-pieces.css",
  `${header}.chess-piece { display: block; background-position: center; background-repeat: no-repeat; background-size: contain; }\n${rules.join("\n")}\n`,
);
out("chess-board.css", `${header}.chess-board-art { background-image: url(${uri("Board.png")}); }\n`);
